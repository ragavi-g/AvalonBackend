const serverUnixTime = () => Math.floor(Date.now() / 1000);

const buildJsonResponse = (
  statusCode,
  { isSuccess, responseMsg, data = {} },
) => ({
  statusCode,
  body: JSON.stringify({
    isSuccess,
    responseMsg,
    data,
    serverDateTime: serverUnixTime(),
  }),
  headers,
});

const handleGLMasterPolicies = async (
  accountId,
  ratingPeriodId,
  generalLiabilityId,
) => {
  const data = sampleGLMasterPolicies.filter((item) => {
    const matchesAccount =
      Number.isNaN(accountId) || item.AccountID === accountId;
    const matchesRating =
      Number.isNaN(ratingPeriodId) || item.RatingPeriodID === ratingPeriodId;
    const matchesGl =
      generalLiabilityId === null ||
      item.GeneralLiabilityId === String(generalLiabilityId);
    return matchesAccount && matchesRating && matchesGl;
  });

  return buildJsonResponse(200, {
    isSuccess: true,
    responseMsg: "Master Policies loaded successfully",
    data,
  });
};

export const handlerGLMasterPolicies = async (event) => {
  const method = (event.httpMethod || "").toUpperCase();
  const path = event.path || "";

  const accountId = Number(event.query?.accountId);
  const ratingPeriodId = Number(event.query?.ratingPeriodId);
  const generalLiabilityId = event.query?.generalLiabilityId
    ? Number(event.query.generalLiabilityId)
    : null;
  if (method === "OPTIONS") {
    return {
      statusCode: 204,
      body: "",
      headers,
    };
  }

  try {
    if (path === "/gl/master_policies" && method === "GET") {
      return await handleGLMasterPolicies(accountId, ratingPeriodId, generalLiabilityId);
    }

    return buildJsonResponse(404, {
      isSuccess: false,
      responseMsg: "Route not found",
      data: {},
    });
  } catch (error) {
    console.error(error);

    return buildJsonResponse(500, {
      isSuccess: false,
      responseMsg: error.message,
      data: {},
    });
  }
};

const server = http.createServer(async (req, res) => {
  let body = "";

  req.on("data", (chunk) => {
    body += chunk;
  });

  req.on("end", async () => {
    const url = new URL(req.url, `http://${req.headers.host}`);
    const event = {
      httpMethod: req.method,
      path: url.pathname,
      query: Object.fromEntries(url.searchParams),
      body,
    };

    const response = await handlerGLMasterPolicies(event);

    res.writeHead(response.statusCode, response.headers);
    res.end(response.body);
  });
});

