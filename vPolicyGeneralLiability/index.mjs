const serverUnixTime = () => Math.floor(Date.now() / 1000);

const buildJsonResponse = (
  statusCode,
  { isSuccess, responseMsg, data = {} },
) => ({
  statusCode,
  body: JSON.stringify({
    isSuccess,
    responseMsg,
    data,
    serverDateTime: serverUnixTime(),
  }),
  headers,
});

const handlePolicyGeneralLiability = async (accountId, ratingPeriodId) => {
  const data = samplePolicyGeneralLiability.filter((item) => {
    const matchesAccount =
      Number.isNaN(accountId) || item.AccountID === accountId;
    const matchesRating =
      Number.isNaN(ratingPeriodId) || item.RatingPeriodID === ratingPeriodId;
    return matchesAccount && matchesRating;
  });

  return buildJsonResponse(200, {
    isSuccess: true,
    responseMsg: "Policy General Liability loaded successfully",
    data,
  });
};

export const handlerPolicyGeneralLiability = async (event) => {
  const method = (event.httpMethod || "").toUpperCase();
  const path = event.path || "";
  const accountId = Number(event.query?.accountId);
  const ratingPeriodId = Number(event.query?.ratingPeriodId);

  if (method === "OPTIONS") {
    return {
      statusCode: 204,
      body: "",
      headers,
    };
  }

  try {
    if (path === "/policy_general_liability" && method === "GET") {
      return await handlePolicyGeneralLiability(accountId, ratingPeriodId);
    }

    return buildJsonResponse(404, {
      isSuccess: false,
      responseMsg: "Route not found",
      data: {},
    });
  } catch (error) {
    console.error(error);

    return buildJsonResponse(500, {
      isSuccess: false,
      responseMsg: error.message,
      data: {},
    });
  }
};

const server = http.createServer(async (req, res) => {
  let body = "";

  req.on("data", (chunk) => {
    body += chunk;
  });

  req.on("end", async () => {
    const url = new URL(req.url, `http://${req.headers.host}`);
    const event = {
      httpMethod: req.method,
      path: url.pathname,
      query: Object.fromEntries(url.searchParams),
      body,
    };

    const response = await handlerPolicyGeneralLiability(event);

    res.writeHead(response.statusCode, response.headers);
    res.end(response.body);
  });
});

const start = async () => {
  try {
    server.listen(PORT, () => {
      console.log(`Server running on http://localhost:${PORT}`);

      console.log(
        `Test URL: http://localhost:${PORT}/policy_general_liability`,
      );
    });
  } catch (error) {
    console.error("Failed to start application:", error.message);
    process.exit(1);
  }
};

