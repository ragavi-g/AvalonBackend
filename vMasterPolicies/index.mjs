const PORT = process.env.PORT || 3005;

const headers = {
  "Content-Type": "application/json",
  "Access-Control-Allow-Headers": "*",
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "OPTIONS,GET,POST",
};

const serverUnixTime = () => Math.floor(Date.now() / 1000);

const buildJsonResponse = (
  statusCode,
  { isSuccess, responseMsg, data = {} },
) => ({
  statusCode,
  body: JSON.stringify({
    isSuccess,
    responseMsg,
    data,
    serverDateTime: serverUnixTime(),
  }),
  headers,
});

const handleMasterPolicies = async () => {
  return buildJsonResponse(200, {
    isSuccess: true,
    responseMsg: "Master Policies loaded successfully",
    data: sampleMasterPolicies,
  });
};

export const handlerMasterPolicies = async (event) => {
  const method = (event.httpMethod || "").toUpperCase();
  const path = event.path || "";

  if (method === "OPTIONS") {
    return {
      statusCode: 204,
      body: "",
      headers,
    };
  }

  try {
    if (path === "/master_policies" && method === "GET") {
      return await handleMasterPolicies();
    }

    return buildJsonResponse(404, {
      isSuccess: false,
      responseMsg: "Route not found",
      data: {},
    });
  } catch (error) {
    console.error(error);

    return buildJsonResponse(500, {
      isSuccess: false,
      responseMsg: error.message,
      data: {},
    });
  }
};

const server = http.createServer(async (req, res) => {
  let body = "";

  req.on("data", (chunk) => {
    body += chunk;
  });

  req.on("end", async () => {
    const event = {
      httpMethod: req.method,
      path: req.url,
      body,
    };

    const response = await handlerMasterPolicies(event);

    res.writeHead(response.statusCode, response.headers);
    res.end(response.body);
  });
});

const start = async () => {
  try {
    server.listen(PORT, () => {
      console.log(`Server running on http://localhost:${PORT}`);

      console.log(`Test URL: http://localhost:${PORT}/master_policies`);
    });
  } catch (error) {
    console.error("Failed to start application:", error.message);
    process.exit(1);
  }
};

const shutdown = async () => {
  try {
    console.log("Application shutdown completed");
  } catch (err) {
    console.error(err);
  }
};

process.on("SIGINT", async () => {
  await shutdown();
  process.exit(0);
});

process.on("SIGTERM", async () => {
  await shutdown();
  process.exit(0);
});

process.on("exit", shutdown);

start();
